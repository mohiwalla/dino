// Chrome's 1x offline sprites (components/neterror/resources/images/default_100_percent/
// offline/100-offline-sprite.png), redrawn pixel for pixel as part-labelled bitmaps for
// parseBitmap. Rows are top row first; one character per sprite pixel.
//
// Only the ink is kept: Chrome pads every sprite with a 1-2 px background-coloured outline
// (it masks the ground line in 2D), so each bitmap is the ink's bounding box and models.ts
// stretches it to the sim box (T-Rex ink 40 x 43 -> 44 x 47). Frames of one model share
// the same box so they line up when swapped.
//
// Characters name the part a pixel belongs to, which drives the 3D sculpting (see the
// models-*.ts builders); every part is ink except the eye. '.' is empty.

import { SLOT } from '../config';
import type { TrexFrame } from '../types';

export const PART = {
  BODY: 1,
  HEAD: 2,
  EYE: 3,
  ARM: 4,
  BACK_LEG: 5,
  FRONT_LEG: 6,
  LEFT_ARM: 7,
  RIGHT_ARM: 8,
  WING: 9,
} as const;

export type Part = (typeof PART)[keyof typeof PART];

/** Character -> part, for parseBitmap. */
export const PART_LEGEND: Readonly<Record<string, Part>> = {
  '#': PART.BODY,
  h: PART.HEAD,
  o: PART.EYE,
  a: PART.ARM,
  b: PART.BACK_LEG,
  f: PART.FRONT_LEG,
  l: PART.LEFT_ARM,
  r: PART.RIGHT_ARM,
  w: PART.WING,
};

/** Character -> voxel material slot, for drawing the sprites flat (2D icons, extrusions). */
export const SLOT_LEGEND: Readonly<Record<string, number>> = Object.fromEntries(
  Object.keys(PART_LEGEND).map((c) => [c, c === 'o' ? SLOT.EYE : SLOT.INK]),
);

